//! `AudioWorklet` JavaScript Generator
//!
//! Generates the `AudioWorkletProcessor` JavaScript using probar-js-gen DSL.
//! Zero raw JavaScript strings - compile-time validated, property-tested.
//!
//! # Why DSL-Generated
//!
//! Raw JavaScript strings bypass the Rust compiler. Using probar-js-gen:
//! - Identifier validation (no reserved words, no invalid chars)
//! - Manifest-based immutability enforcement (hash verification)
//! - Property-based testing catches edge cases
//! - Deterministic output (same input = same output)
//!
//! # References
//! - DO-178C (2011) Section 6.3.5: Configuration management
//! - Leveson (2012) "Engineering a Safer World" - Traceability

// Allow expect on known-good static identifiers validated at compile time
#![allow(clippy::expect_used)]

use probar_js_gen::prelude::*;

/// Ring buffer header size in bytes (must match `ring_buffer.rs`)
const HEADER_SIZE: u32 = 64;

/// Write index offset in header (in i32 units)
const WRITE_IDX_OFFSET: u32 = 0;

/// Read index offset in header (in i32 units)
const READ_IDX_OFFSET: u32 = 1;

/// Capacity offset in header (in i32 units)
const CAPACITY_OFFSET: u32 = 2;

/// Generate the `AudioWorklet` processor JavaScript
///
/// This creates an `AudioWorkletProcessor` class that:
/// 1. Receives `SharedArrayBuffer` via port message
/// 2. Writes audio samples to ring buffer using Atomics
/// 3. Notifies worker thread of new samples
///
/// # Panics
///
/// Panics if any identifier is invalid (should never happen with static strings).
#[must_use]
pub fn generate_audioworklet_js() -> String {
    // Build the class
    let class = JsClassBuilder::new("WhisperAudioProcessor")
        .expect("WhisperAudioProcessor is valid")
        .extends("AudioWorkletProcessor")
        .expect("AudioWorkletProcessor is valid")
        .constructor(build_constructor(
            HEADER_SIZE,
            WRITE_IDX_OFFSET,
            READ_IDX_OFFSET,
            CAPACITY_OFFSET,
        ))
        .method("initBuffer", &["sharedBuffer"], build_init_buffer_method())
        .expect("initBuffer is valid")
        .method(
            "process",
            &["inputs", "outputs", "parameters"],
            build_process_method(),
        )
        .expect("process is valid")
        .method(
            "writeToBuffer",
            &["samples"],
            build_write_to_buffer_method(),
        )
        .expect("writeToBuffer is valid")
        .build();

    // Build the module
    let module = JsModuleBuilder::new()
        .comment("WhisperAudioProcessor - AudioWorklet for real-time audio capture")
        .comment("Generated by probar-js-gen DSL - DO NOT EDIT MANUALLY")
        .comment("")
        .comment("Runs in AudioWorkletGlobalScope (NOT Window)")
        .comment("Uses Atomics for lock-free ring buffer communication")
        .class(class)
        .register_processor("whisper-audio-processor", "WhisperAudioProcessor")
        .expect("registerProcessor identifiers valid")
        .build();

    generate(&module)
}

/// Build constructor body
fn build_constructor(
    header_size: u32,
    write_idx: u32,
    read_idx: u32,
    capacity_idx: u32,
) -> Vec<Stmt> {
    // Helper for member assignment: this.xxx = value
    let this_assign = |member: &str, value: Expr| {
        Stmt::member_assign(Expr::this(), member, value).expect("known-good member")
    };

    vec![
        Stmt::comment("Ring buffer state"),
        this_assign("ringBuffer", Expr::null()),
        this_assign("headerView", Expr::null()),
        this_assign("dataView", Expr::null()),
        this_assign("capacity", Expr::num(0)),
        this_assign("samplesWritten", Expr::num(0)),
        this_assign("underruns", Expr::num(0)),
        Stmt::comment("Constants matching Rust ring_buffer.rs"),
        this_assign("HEADER_SIZE", Expr::num(header_size)),
        this_assign("WRITE_IDX_OFFSET", Expr::num(write_idx)),
        this_assign("READ_IDX_OFFSET", Expr::num(read_idx)),
        this_assign("CAPACITY_OFFSET", Expr::num(capacity_idx)),
        Stmt::comment("Handle messages from main thread"),
        build_port_onmessage_handler(),
    ]
}

/// Build the port.onmessage handler
fn build_port_onmessage_handler() -> Stmt {
    let id = |s: &str| Expr::ident(s).expect("known-good identifier");
    let dot = |e: Expr, prop: &str| e.dot(prop).expect("known-good property");

    // this.port.onmessage = (event) => { ... }
    let handler_body = vec![
        // if (event.data.type === 'init')
        Stmt::if_then(
            dot(dot(id("event"), "data"), "type").eq(Expr::str("init")),
            vec![
                // this.initBuffer(event.data.buffer)
                Stmt::expr(
                    dot(Expr::this(), "initBuffer")
                        .call(vec![dot(dot(id("event"), "data"), "buffer")]),
                ),
            ],
        ),
        // else if (event.data.type === 'reset')
        Stmt::if_then(
            dot(dot(id("event"), "data"), "type").eq(Expr::str("reset")),
            vec![
                Stmt::member_assign(Expr::this(), "samplesWritten", Expr::num(0))
                    .expect("samplesWritten is valid"),
                Stmt::member_assign(Expr::this(), "underruns", Expr::num(0))
                    .expect("underruns is valid"),
            ],
        ),
    ];

    // this.port.onmessage = (event) => { body }
    Stmt::member_assign(
        dot(Expr::this(), "port"),
        "onmessage",
        Expr::arrow_block(&["event"], handler_body).expect("event is valid param"),
    )
    .expect("onmessage is valid")
}

/// Build initBuffer method body
fn build_init_buffer_method() -> Vec<Stmt> {
    let id = |s: &str| Expr::ident(s).expect("known-good identifier");
    let dot = |e: Expr, prop: &str| e.dot(prop).expect("known-good property");
    let this_assign = |member: &str, value: Expr| {
        Stmt::member_assign(Expr::this(), member, value).expect("known-good member")
    };

    vec![
        // this.ringBuffer = sharedBuffer
        this_assign("ringBuffer", id("sharedBuffer")),
        // this.headerView = new Int32Array(sharedBuffer, 0, this.HEADER_SIZE / 4)
        this_assign(
            "headerView",
            id("Int32Array").new_expr(vec![
                id("sharedBuffer"),
                Expr::num(0),
                dot(Expr::this(), "HEADER_SIZE").div(Expr::num(4)),
            ]),
        ),
        // this.capacity = Atomics.load(this.headerView, this.CAPACITY_OFFSET)
        this_assign(
            "capacity",
            dot(id("Atomics"), "load").call(vec![
                dot(Expr::this(), "headerView"),
                dot(Expr::this(), "CAPACITY_OFFSET"),
            ]),
        ),
        // this.dataView = new Float32Array(sharedBuffer, this.HEADER_SIZE, this.capacity)
        this_assign(
            "dataView",
            id("Float32Array").new_expr(vec![
                id("sharedBuffer"),
                dot(Expr::this(), "HEADER_SIZE"),
                dot(Expr::this(), "capacity"),
            ]),
        ),
        // console.log('[AudioWorklet] Initialized with capacity:', this.capacity, 'samples')
        Stmt::expr(dot(id("console"), "log").call(vec![
            Expr::str("[AudioWorklet] Initialized with capacity:"),
            dot(Expr::this(), "capacity"),
            Expr::str("samples"),
        ])),
    ]
}

/// Build process method body
fn build_process_method() -> Vec<Stmt> {
    let id = |s: &str| Expr::ident(s).expect("known-good identifier");
    let dot = |e: Expr, prop: &str| e.dot(prop).expect("known-good property");

    vec![
        // const input = inputs[0]
        Stmt::const_decl("input", id("inputs").index(Expr::num(0))).expect("input is valid"),
        // if (!input || input.length === 0) { return true; }
        Stmt::if_then(
            id("input")
                .not()
                .or(dot(id("input"), "length").eq(Expr::num(0))),
            vec![Stmt::ret_val(Expr::bool(true))],
        ),
        // const samples = input[0] (mono channel)
        Stmt::const_decl("samples", id("input").index(Expr::num(0))).expect("samples is valid"),
        // if (!samples || samples.length === 0) { return true; }
        Stmt::if_then(
            id("samples")
                .not()
                .or(dot(id("samples"), "length").eq(Expr::num(0))),
            vec![Stmt::ret_val(Expr::bool(true))],
        ),
        // if (!this.ringBuffer) { return true; }
        Stmt::if_then(
            dot(Expr::this(), "ringBuffer").not(),
            vec![Stmt::ret_val(Expr::bool(true))],
        ),
        // const written = this.writeToBuffer(samples)
        Stmt::const_decl(
            "written",
            dot(Expr::this(), "writeToBuffer").call(vec![id("samples")]),
        )
        .expect("written is valid"),
        // this.samplesWritten += written
        Stmt::add_assign(dot(Expr::this(), "samplesWritten"), id("written")),
        // if (written < samples.length) { this.underruns++; }
        Stmt::if_then(
            id("written").lt(dot(id("samples"), "length")),
            vec![Stmt::post_increment(dot(Expr::this(), "underruns"))],
        ),
        // return true (keep processor alive)
        Stmt::ret_val(Expr::bool(true)),
    ]
}

/// Build writeToBuffer method body
fn build_write_to_buffer_method() -> Vec<Stmt> {
    let id = |s: &str| Expr::ident(s).expect("known-good identifier");
    let dot = |e: Expr, prop: &str| e.dot(prop).expect("known-good property");

    vec![
        // const writeIdx = Atomics.load(this.headerView, this.WRITE_IDX_OFFSET)
        Stmt::const_decl(
            "writeIdx",
            dot(id("Atomics"), "load").call(vec![
                dot(Expr::this(), "headerView"),
                dot(Expr::this(), "WRITE_IDX_OFFSET"),
            ]),
        )
        .expect("writeIdx is valid"),
        // const readIdx = Atomics.load(this.headerView, this.READ_IDX_OFFSET)
        Stmt::const_decl(
            "readIdx",
            dot(id("Atomics"), "load").call(vec![
                dot(Expr::this(), "headerView"),
                dot(Expr::this(), "READ_IDX_OFFSET"),
            ]),
        )
        .expect("readIdx is valid"),
        // let available
        Stmt::let_decl("available", Expr::num(0)).expect("available is valid"),
        // if (writeIdx >= readIdx) { available = capacity - 1 - (writeIdx - readIdx); }
        // else { available = readIdx - writeIdx - 1; }
        Stmt::if_else(
            id("writeIdx").ge(id("readIdx")),
            vec![Stmt::assign(
                "available",
                dot(Expr::this(), "capacity")
                    .sub(Expr::num(1))
                    .sub(id("writeIdx").sub(id("readIdx"))),
            )
            .expect("available assignment")],
            vec![Stmt::assign(
                "available",
                id("readIdx").sub(id("writeIdx")).sub(Expr::num(1)),
            )
            .expect("available assignment")],
        ),
        // const toWrite = Math.min(samples.length, available)
        Stmt::const_decl(
            "toWrite",
            dot(id("Math"), "min").call(vec![dot(id("samples"), "length"), id("available")]),
        )
        .expect("toWrite is valid"),
        // if (toWrite === 0) { return 0; }
        Stmt::if_then(
            id("toWrite").eq(Expr::num(0)),
            vec![Stmt::ret_val(Expr::num(0))],
        ),
        // let idx = writeIdx
        Stmt::let_decl("idx", id("writeIdx")).expect("idx is valid"),
        // for (let i = 0; i < toWrite; i++) { ... }
        Stmt::for_loop(
            "i",
            Expr::num(0),
            id("toWrite"),
            vec![
                // this.dataView[idx] = samples[i]
                Stmt::expr(
                    dot(Expr::this(), "dataView")
                        .index(id("idx"))
                        .assign(id("samples").index(id("i"))),
                ),
                // idx = (idx + 1) % this.capacity
                Stmt::assign(
                    "idx",
                    id("idx")
                        .add(Expr::num(1))
                        .modulo(dot(Expr::this(), "capacity")),
                )
                .expect("idx assignment"),
            ],
        )
        .expect("for loop is valid"),
        // Atomics.store(this.headerView, this.WRITE_IDX_OFFSET, idx)
        Stmt::expr(dot(id("Atomics"), "store").call(vec![
            dot(Expr::this(), "headerView"),
            dot(Expr::this(), "WRITE_IDX_OFFSET"),
            id("idx"),
        ])),
        // Atomics.notify(this.headerView, this.WRITE_IDX_OFFSET, 1)
        Stmt::expr(dot(id("Atomics"), "notify").call(vec![
            dot(Expr::this(), "headerView"),
            dot(Expr::this(), "WRITE_IDX_OFFSET"),
            Expr::num(1),
        ])),
        // return toWrite
        Stmt::ret_val(id("toWrite")),
    ]
}

